public class Print1to10Numbers {
    public static void main(String[] args) {
        // Initialize the counter variable at 1
        int i = 1;

        // The loop runs as long as i is less than or equal to 10
        while (i <= 10) {
            System.out.println(i);
            
            // Increment i by 1 in each iteration
            i++; 
        }
    }
}